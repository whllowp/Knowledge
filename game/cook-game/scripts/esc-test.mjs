import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1024, height: 640 } });
const errs = [];
page.on('pageerror', e => errs.push(e.message));
await page.goto('file:///E:/game/cook-game/dist/index.html');
await page.waitForTimeout(500);
await page.getByRole('button', { name: /设置/ }).click();
await page.waitForTimeout(300);
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
const menuAfterSettings = await page.evaluate(() => [...document.querySelectorAll('.screen.active')].map(s=>s.id));
await page.getByRole('button', { name: /玩法说明/ }).click();
await page.waitForTimeout(300);
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
const menuAfterHelp = await page.evaluate(() => [...document.querySelectorAll('.screen.active')].map(s=>s.id));
await page.evaluate(() => window.__SIZZLE__.start('fp', 1, 1));
await page.waitForTimeout(700);
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
await page.locator('#screen-pause [data-action="settings"]').click();
await page.waitForTimeout(300);
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
const pauseAfterSettings = await page.evaluate(() => [...document.querySelectorAll('.screen.active')].map(s=>s.id));
console.log({ menuAfterSettings, menuAfterHelp, pauseAfterSettings, errs });
await browser.close();

/** Look up a single fish by id. Returns the object, or null when unknown. */
export function fishById(id) {
  if (typeof id !== 'string') return null;
  for (let i = 0; i < FISH.length; i++) {
    if (FISH[i].id === id) return FISH[i];
  }
  return null;
}

/** All fish of a given rarity tier. Returns [] for out-of-range input. */
export function fishByRarity(r) {
  const tier = Number(r);
  if (!Number.isInteger(tier) || tier < 1 || tier > 5) return [];
  return FISH.filter((f) => f.rarity === tier);
}
